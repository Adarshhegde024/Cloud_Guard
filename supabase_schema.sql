-- 1. USERS TABLE
CREATE TABLE IF NOT EXISTS public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    phone TEXT NOT NULL DEFAULT '',
    password_hash TEXT NOT NULL,
    face_enrollment TEXT,
    checkin_interval INTEGER NOT NULL DEFAULT 30,
    checkin_frequency_value INTEGER NOT NULL DEFAULT 30,
    checkin_frequency_unit TEXT NOT NULL DEFAULT 'days',
    checkin_frequency_seconds INTEGER NOT NULL DEFAULT 2592000,
    grace_period_value INTEGER NOT NULL DEFAULT 72,
    grace_period_unit TEXT NOT NULL DEFAULT 'hours',
    grace_period_seconds INTEGER NOT NULL DEFAULT 259200,
    date_of_birth TEXT NOT NULL DEFAULT '',
    identity_status TEXT NOT NULL DEFAULT 'verified',
    account_state TEXT NOT NULL DEFAULT 'ACTIVE',
    last_checkin_at TIMESTAMPTZ,
    next_checkin_deadline TIMESTAMPTZ,
    grace_period_started_at TIMESTAMPTZ,
    grace_period_deadline TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Allow anon all on users" ON public.users;
CREATE POLICY "Allow anon all on users" ON public.users FOR ALL TO anon USING (true) WITH CHECK (true);
DROP POLICY IF EXISTS "Allow authenticated all on users" ON public.users;
CREATE POLICY "Allow authenticated all on users" ON public.users FOR ALL TO authenticated USING (true) WITH CHECK (true);

